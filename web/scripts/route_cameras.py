def lerp(a: tuple[float, float], b: tuple[float, float], t: float) -> tuple[float, float]:
    return (round(a[0] + (b[0] - a[0]) * t, 5), round(a[1] + (b[1] - a[1]) * t, 5))


def road_cameras() -> list[dict]:
    """Дорожные камеры 0–95: улица i % 25, участок i // 25 из четырёх по длине улицы."""
    cams = []
    for i in range(96):
        name, a, b = STREETS[i % len(STREETS)]
        k = i // len(STREETS)
        lat, lon = lerp(a, b, (k + 0.5) / 4)
        cams.append({"id": str(i), "kind": "road", "lat": lat, "lon": lon,
                     "address": f"{name}, участок {k + 1}", "city": "Москва"})
    return cams


def main() -> None:
    cameras = road_cameras()
    cameras += [{"id": pid, "kind": "parking", "lat": lat, "lon": lon, "address": addr,
                 "city": "Москва", "zone": zone} for pid, addr, lat, lon, zone in PARKING]
    routes = []
    for rid, name, path, (pid, city, addr, lat, lon) in ROUTES:
        cameras += [{"id": cid, "kind": "road", "lat": la, "lon": lo, "address": seg, "city": c}
                    for cid, c, seg, la, lo in path]
        cameras.append({"id": pid, "kind": "parking", "lat": lat, "lon": lon,
                        "address": addr, "city": city})
        routes.append({"id": rid, "name": name, "cameraIds": [p[0] for p in path], "parkingId": pid})
    OUT_CAMERAS.write_text(json.dumps({"cameras": cameras, "routes": routes},
                                      ensure_ascii=False, indent=1) + "\n")
    print(f"{len(cameras)} камер, {len(routes)} маршрута")


if __name__ == "__main__":
    main()
